    /** @brief Save calibration to mag_calib.txt (exe dir), auto-loaded at next start */
    void saveMagCalibration() {
        std::ofstream f("mag_calib.txt", std::ios::out | std::ios::trunc);
        if (!f.is_open()) return;
        const auto fit = currentMagFit();
        f << "LPMS_MAG_ELLIP_V1\n";
        f << std::setprecision(10);
        for (int i = 0; i < 3; ++i) f << fit.center[i] << (i < 2 ? " " : "\n");
        for (int i = 0; i < 9; ++i) f << fit.M[i] << (i < 8 ? " " : "\n");
        f << fit.coverage << " " << fit.rmsResidual << "\n";

        // 记录校准时刻。椭球拟合把当时环境里的硬铁偏移一并吸收进 center，
        // 而 center 常常远大于地磁场本身；传感器一挪位置这份校准就失效了，
        // 但文件每次启动都会被无条件加载，所以必须能看出它是多久以前做的。
        const long long now = (long long)std::chrono::system_clock::to_time_t(
            std::chrono::system_clock::now());
        f << now << "\n";
        m_magCalibTime.store(now);

        m_magCalibValid.store(true);
    }

    /** @brief Load magnetometer ellipsoid calibration from mag_calib.txt (exe dir) */
    void loadMagCalibration() {
        std::ifstream f("mag_calib.txt");
        if (!f.is_open()) return;
        std::string tag;
        if (!(f >> tag) || tag != "LPMS_MAG_ELLIP_V1") return;  // legacy min/max format discarded
        MagEllipsoidCalib::Result res;
        for (int i = 0; i < 3; ++i) if (!(f >> res.center[i])) return;
        for (int i = 0; i < 9; ++i) if (!(f >> res.M[i])) return;
        if (!(f >> res.coverage >> res.rmsResidual)) { res.coverage = 0; res.rmsResidual = 0; }
        // 文件里只存 center 和 M，物理半轴等派生量必须重算，
        // 否则 GUI 会把未初始化的默认值当成 µT 显示。
        MagEllipsoidCalib::deriveGeometry(res);
        res.ok = true;
        res.radius = 1.0;

        // 旧版本文件没有时间戳行，读不到就记 0（表示"未知"），保持向后兼容。
        long long t = 0;
        if (!(f >> t)) t = 0;

        {
            std::lock_guard<std::mutex> lock(m_magFitMutex);
            m_magFit = res;
        }
        m_magCalibTime.store(t);
        m_magCalibValid.store(true);

        // 一并把上次拟合用的点云读回来，校准窗口才能立刻把椭球和真实数据画在一起，
        // 而不是要等用户重新做一次校准才有东西可看。
        loadMagSamples();
    }

    /**
     * @brief 读回 dumpMagSamples() 写出的 mag_calib_samples.txt。
     *
     * 文件缺失或格式不对都直接放弃：点云只是给校准窗口做可视化用的，
     * 不影响已经加载生效的 center/M。
     */
    void loadMagSamples() {
        std::ifstream f("mag_calib_samples.txt");
        if (!f.is_open()) return;
        std::string tag;
        if (!(f >> tag) || tag != "LPMS_MAG_SAMPLES_V1") return;
        std::string rest;
        std::getline(f, rest);   // 丢掉 n=/ok=/failStep= 那一行的剩余部分

        std::vector<std::array<float, 3>> loaded;
        double x, y, z;
        while (loaded.size() < 20000 && (f >> x >> y >> z))
            loaded.push_back({ (float)x, (float)y, (float)z });
        if (loaded.empty()) return;

        std::lock_guard<std::mutex> lock(m_magCalibMutex);
        m_magSamples.swap(loaded);
    }

