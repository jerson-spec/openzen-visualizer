    // === Field survey：桌面网格扫描读数记录 ===
    // Field Survey 窗口把一个格点的统计量（静止窗口内的平均航向/|B|）算好
    // 后调这里，逐行追加到 field_survey.txt。文件 I/O 与 imu_data 记录一样
    // 全部收在 SensorThread 内、由互斥锁保护，GUI 线程只传入结果。

    /// field_survey 文件名（写在 exe 运行目录）
    static constexpr const char* kSurveyFileName = "field_survey.txt";

    /// 一次 Mark 的内容：一个格点上静止窗口的统计快照
    struct SurveyMark {
        double sensorTime;       ///< 标记时刻的传感器时间戳 (s)
        char label[40];          ///< 格点标签（如 A1）
        double headingDeg;       ///< 圆周平均的倾角补偿磁航向
        double headingDevDeg;    ///< 窗口内样本偏离圆周平均的最大值
        double fieldMag;         ///< 校准后 |B| 均值
        double fieldMagDev;      ///< 窗口内 |B| 偏离均值的最大值
        double magUnit[3];       ///< 校准单位向量均值（传感器系，|·|≈1）
        double magB[3];          ///< 固件磁通道均值
        double acc[3];           ///< 加速度均值
        int nStill;              ///< 参与统计的静止样本数
    };

    /**
     * @brief 追加一条网格扫描标记到 field_survey.txt。
     *
     * 按行追加、每条 Mark 后 flush，中途退出最多丢当前一行。首次创建时写
     * UTF-8 BOM + 表头；已存在的文件直接续写，但每次程序启动会补一行
     * "# session" 注释作分隔（解析时跳过 # 开头的行即可）。
     *
     * @return true=写入成功；false=文件打不开
     */
    bool surveyMark(const SurveyMark& m) {
        std::lock_guard<std::mutex> lock(m_surveyFileMutex);
        if (!m_surveyFile.is_open()) {
            std::ifstream probe(kSurveyFileName);
            const bool existed = probe.good();
            probe.close();
            m_surveyFile.open(kSurveyFileName, std::ios::out | std::ios::app | std::ios::binary);
            if (!m_surveyFile.is_open()) return false;

            // 新文件第一件事写 BOM（Excel 友好），再写会话分隔与表头
            if (!existed) {
                const unsigned char bom[] = { 0xEF, 0xBB, 0xBF };
                m_surveyFile.write(reinterpret_cast<const char*>(bom), sizeof(bom));
            }

            char sess[64] = "unknown";
            {
                const std::time_t tt = std::chrono::system_clock::to_time_t(
                    std::chrono::system_clock::now());
                std::tm lt;
                localtime_s(&lt, &tt);
                std::strftime(sess, sizeof(sess), "%Y-%m-%d %H:%M:%S", &lt);
            }
            m_surveyFile << "# session " << sess << "\n";
            if (!existed) {
                m_surveyFile << "DateTime\tLabel\tSensorTime(s)\tHeading(deg)\tHeadingDev(deg)\t"
                               "Bmag(uT)\tBmagDev(uT)\tMagUnit_X\tMagUnit_Y\tMagUnit_Z\t"
                               "MagB_X(uT)\tMagB_Y(uT)\tMagB_Z(uT)\t"
                               "AccX(g)\tAccY(g)\tAccZ(g)\tN\n";
            }
        }

        char dt[64] = "unknown";
        {
            const std::time_t tt = std::chrono::system_clock::to_time_t(
                std::chrono::system_clock::now());
            std::tm lt;
            localtime_s(&lt, &tt);
            std::strftime(dt, sizeof(dt), "%Y-%m-%d %H:%M:%S", &lt);
        }

        m_surveyFile << std::fixed << std::setprecision(6)
            << dt << "\t" << m.label << "\t" << m.sensorTime << "\t"
            << m.headingDeg << "\t" << m.headingDevDeg << "\t"
            << m.fieldMag << "\t" << m.fieldMagDev << "\t"
            << m.magUnit[0] << "\t" << m.magUnit[1] << "\t" << m.magUnit[2] << "\t"
            << m.magB[0] << "\t" << m.magB[1] << "\t" << m.magB[2] << "\t"
            << m.acc[0] << "\t" << m.acc[1] << "\t" << m.acc[2] << "\t"
            << m.nStill << "\n";
        m_surveyFile.flush();
        m_surveyRows.fetch_add(1);
        return true;
    }

